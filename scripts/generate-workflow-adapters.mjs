import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
for (const workflow of ["join", "goals", "card", "clear", "fanout", "steward"]) {
  const body = readFileSync(new URL(`skills/squad/references/${workflow}.md`, root), "utf8");
  const description = body.match(/^description: (.+)$/m)?.[1];
  if (!description) throw new Error(`Missing description for ${workflow}`);
  for (const [runtime, path] of [
    [".claude", `commands/squad/${workflow}.md`],
    [".agents", `codex/prompts/squad-${workflow}.md`],
  ]) {
    const skill = `${runtime}/skills/squad`;
    const adapter = `---\ndescription: ${description}\n---\n\n<!-- Generated by scripts/generate-workflow-adapters.mjs; do not edit. -->\nRead \`${skill}/SKILL.md\`, then follow \`${skill}/references/${workflow}.md\` with the user's request: $ARGUMENTS. Resolve these paths from the repository root. If the skill is missing, report that Squad needs to be installed in this repository.\n`;
    const file = new URL(path, root);
    if (check) {
      if (readFileSync(file, "utf8") !== adapter) throw new Error(`Stale adapter: ${fileURLToPath(file)}`);
    } else writeFileSync(file, adapter);
  }
}
